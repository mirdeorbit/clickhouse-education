CREATE TABLE IF NOT EXISTS polygons (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    city VARCHAR(100) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE polygons OWNER TO REPLICATION_GROUP;
ALTER TABLE polygons REPLICA IDENTITY FULL;

COMMENT ON TABLE polygons IS 'Зоны доставки (территории обслуживания)';
COMMENT ON COLUMN polygons.id IS 'Уникальный идентификатор полигона';
COMMENT ON COLUMN polygons.name IS 'Название зоны доставки';
COMMENT ON COLUMN polygons.city IS 'Город, к которому относится зона';
COMMENT ON COLUMN polygons.is_active IS 'Активна ли зона доставки';
COMMENT ON COLUMN polygons.created_at IS 'Дата создания полигона';


CREATE TABLE IF NOT EXISTS shops (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    address VARCHAR(255) NOT NULL,
    delivery_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    start_work_time TIME NOT NULL,
    end_work_time TIME NOT NULL,
    city VARCHAR(100) NOT NULL,
    polygon_id INTEGER,

    CONSTRAINT fk_shops_polygon
        FOREIGN KEY (polygon_id) REFERENCES polygons(id)
        ON DELETE SET NULL
);

ALTER TABLE shops OWNER TO REPLICATION_GROUP;
ALTER TABLE shops REPLICA IDENTITY FULL;

COMMENT ON TABLE shops IS 'Магазины, из которых осуществляется сборка и доставка заказов';
COMMENT ON COLUMN shops.address IS 'Фактический адрес магазина';
COMMENT ON COLUMN shops.delivery_enabled IS 'Включена ли сборка и доставка заказов';
COMMENT ON COLUMN shops.start_work_time IS 'Время начала работы магазина';
COMMENT ON COLUMN shops.end_work_time IS 'Время окончания работы магазина';
COMMENT ON COLUMN shops.polygon_id IS 'Полигон (зона доставки), к которому относится магазин';
COMMENT ON COLUMN shops.city IS 'Город расположения магазина';

CREATE TABLE IF NOT EXISTS couriers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    patronymic VARCHAR(100),
    phone VARCHAR(20) NOT NULL UNIQUE,
    email VARCHAR(255) UNIQUE,
    inn VARCHAR(20) UNIQUE,
    city VARCHAR(100) NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('blocked', 'on_work', 'not_on_work')),
    company VARCHAR(255),
    self_employed BOOLEAN NOT NULL DEFAULT FALSE,
    timezone VARCHAR(50) NOT NULL,
    polygon_id INTEGER,

    CONSTRAINT fk_courier_polygon
        FOREIGN KEY (polygon_id) REFERENCES polygons(id)
        ON DELETE SET NULL
);

ALTER TABLE couriers OWNER TO REPLICATION_GROUP;
ALTER TABLE couriers REPLICA IDENTITY FULL;


